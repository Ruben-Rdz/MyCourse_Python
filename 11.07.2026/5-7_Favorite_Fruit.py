# Make a list of your three favorite fruits and call it favorite_fruits.
# Write five if statements. Each should check whether a certain kind of fruit is
# in your list. If the fruit is in your list, the if block should print a statement,
# such as You really like bananas!


favorite_fruits = ["apple", "avocado", "mamey", "grapes", "mandarine"]

if "apple" in favorite_fruits:
    print("You really like apples!")
if "avocado" in favorite_fruits:
    print("You really like avocados!")
if "mamey" in favorite_fruits:
    print("You really like mamey!")
if "grapes" in favorite_fruits:
    print("You really like grapes!")
if "mandarine" in favorite_fruits:
    print("You really like mandarines!")
